-- Ludo Master by GameRAX account and friend-request setup
-- Run this script in Supabase Dashboard -> SQL Editor -> New query -> Run.
-- Uses dedicated ludo_* tables only; does not change other project tables.

create table if not exists public.ludo_profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  username text not null unique,
  avatar_emoji text not null default '🎮' check (avatar_emoji in ('🎮','😎','🐱','🐼','🦊','🐸','🐯','🐉','👑','🚀','👾','🦄','⚽','🐺','🥷','🧙')),
  created_at timestamptz not null default now(),
  constraint ludo_username_format check (username = lower(username) and username ~ '^[a-z0-9_]{3,20}$')
);

-- Add the display-picture field to existing installs without affecting current accounts.
alter table public.ludo_profiles
  add column if not exists avatar_emoji text not null default '🎮'
  check (avatar_emoji in ('🎮','😎','🐱','🐼','🦊','🐸','🐯','🐉','👑','🚀','👾','🦄','⚽','🐺','🥷','🧙'));

create table if not exists public.ludo_friend_requests (
  id bigint generated by default as identity primary key,
  sender_id uuid not null references public.ludo_profiles(id) on delete cascade,
  receiver_id uuid not null references public.ludo_profiles(id) on delete cascade,
  status text not null default 'pending' check (status in ('pending','accepted','declined')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint ludo_no_self_invite check (sender_id <> receiver_id)
);

create index if not exists ludo_friend_requests_sender_idx on public.ludo_friend_requests(sender_id, status);
create index if not exists ludo_friend_requests_receiver_idx on public.ludo_friend_requests(receiver_id, status);
create index if not exists ludo_profiles_username_idx on public.ludo_profiles(username);

alter table public.ludo_profiles enable row level security;
alter table public.ludo_friend_requests enable row level security;

drop policy if exists "Authenticated users can find Ludo usernames" on public.ludo_profiles;
create policy "Authenticated users can find Ludo usernames"
on public.ludo_profiles for select to authenticated using (true);

drop policy if exists "Users can create their own Ludo profile" on public.ludo_profiles;
create policy "Users can create their own Ludo profile"
on public.ludo_profiles for insert to authenticated with check (auth.uid() = id);

drop policy if exists "Users can update their own Ludo profile" on public.ludo_profiles;
create policy "Users can update their own Ludo profile"
on public.ludo_profiles for update to authenticated using (auth.uid() = id) with check (auth.uid() = id);

drop policy if exists "Users can view their own friend requests" on public.ludo_friend_requests;
create policy "Users can view their own friend requests"
on public.ludo_friend_requests for select to authenticated
using (auth.uid() = sender_id or auth.uid() = receiver_id);

drop policy if exists "Users can invite other Ludo players" on public.ludo_friend_requests;
create policy "Users can invite other Ludo players"
on public.ludo_friend_requests for insert to authenticated
with check (auth.uid() = sender_id and sender_id <> receiver_id and status = 'pending');

drop policy if exists "Receivers can respond to friend requests" on public.ludo_friend_requests;
create policy "Receivers can respond to friend requests"
on public.ludo_friend_requests for update to authenticated
using (auth.uid() = receiver_id)
with check (auth.uid() = receiver_id and status in ('accepted','declined'));

grant select, insert, update on public.ludo_profiles to authenticated;
grant select, insert, update on public.ludo_friend_requests to authenticated;
grant usage, select on sequence public.ludo_friend_requests_id_seq to authenticated;

-- Online friend matches. Uses a UUID room id so the realtime channel name is not guessable.
create table if not exists public.ludo_game_invites (
  id uuid primary key default gen_random_uuid(),
  sender_id uuid not null references public.ludo_profiles(id) on delete cascade,
  receiver_id uuid not null references public.ludo_profiles(id) on delete cascade,
  status text not null default 'pending' check (status in ('pending','accepted','declined','finished','cancelled')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint ludo_game_invite_no_self check (sender_id <> receiver_id)
);

create index if not exists ludo_game_invites_sender_idx on public.ludo_game_invites(sender_id, status, created_at desc);
create index if not exists ludo_game_invites_receiver_idx on public.ludo_game_invites(receiver_id, status, created_at desc);
alter table public.ludo_game_invites enable row level security;

drop policy if exists "Players can view their own game invites" on public.ludo_game_invites;
create policy "Players can view their own game invites"
on public.ludo_game_invites for select to authenticated
using (auth.uid() = sender_id or auth.uid() = receiver_id);

drop policy if exists "Players can invite friends to games" on public.ludo_game_invites;
create policy "Players can invite friends to games"
on public.ludo_game_invites for insert to authenticated
with check (auth.uid() = sender_id and sender_id <> receiver_id and status = 'pending');

drop policy if exists "Invitees can respond to game invites" on public.ludo_game_invites;
create policy "Invitees can respond to game invites"
on public.ludo_game_invites for update to authenticated
using (auth.uid() = receiver_id and status = 'pending')
with check (auth.uid() = receiver_id and status in ('accepted','declined'));

drop policy if exists "Players can finish their game invites" on public.ludo_game_invites;
create policy "Players can finish their game invites"
on public.ludo_game_invites for update to authenticated
using ((auth.uid() = sender_id or auth.uid() = receiver_id) and status = 'accepted')
with check ((auth.uid() = sender_id or auth.uid() = receiver_id) and status in ('accepted','finished','cancelled'));

grant select, insert, update on public.ludo_game_invites to authenticated;


